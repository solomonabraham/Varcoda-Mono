#!/usr/bin/env python3
"""Run every validation step and write tests/font-validation/REPORT.md.

    python3 tests/font-validation/validate.py

1. the project's own test-suite (pytest: font-validation + rendering-tests)
2. fontbakery's "universal" profile on the TTF and OTF builds, if installed

Exit status is non-zero if a test fails or fontbakery reports a FAIL.
"""
from __future__ import annotations

import collections
import json
import os
import platform
import re
import shutil
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
STYLES = ["Light", "Regular", "Medium", "SemiBold", "Bold",
          "LightItalic", "Italic", "MediumItalic", "SemiBoldItalic", "BoldItalic"]

# why the remaining fontbakery findings are accepted
NOTES = {
    "soft_hyphen": "U+00AD is part of Latin-1 Supplement, which this project covers completely.",
    "contour_count": "Only U+00AD: it is drawn as a visible hyphen on purpose, so that an otherwise invisible "
                     "character shows up in source code.",
    "alt_caron": "fontbakery cannot inspect the caron of ď because the glyph is an outline, not a composite; "
                 "ď ľ ť Ľ use the apostrophe-shaped caron (see the specimen).",
    "opentype/monospace": "Crash inside fontbakery itself (KeyError: 'glyf'): the check reads the glyf table, "
                          "which CFF fonts do not have. The properties it checks are covered by the test-suite.",
}


def versions():
    out = collections.OrderedDict()
    from importlib import metadata
    out["Python"] = platform.python_version()
    for dist in ["fonttools", "ufo2ft", "ufoLib2", "skia-pathops", "ttfautohint-py", "afdko", "cffsubr", "uharfbuzz",
                 "freetype-py", "pillow", "numpy", "pygments", "opentype-sanitizer", "pytest", "fontbakery"]:
        try:
            out[dist] = metadata.version(dist)
        except metadata.PackageNotFoundError:
            out[dist] = "not installed"
    try:
        import freetype
        out["FreeType library"] = ".".join(str(v) for v in freetype.version())
    except Exception:
        pass
    for exe, args in [("google-chrome", ["--version"]), ("chromium", ["--version"]), ("fc-scan", ["--version"])]:
        p = shutil.which(exe)
        if p:
            r = subprocess.run([p] + args, capture_output=True, text=True)
            out[exe] = (r.stdout or r.stderr).strip().split("\n")[0]
    return out


def run_pytest():
    res = subprocess.run([sys.executable, "-m", "pytest", os.path.join(ROOT, "tests"), "-q", "-p", "no:cacheprovider"],
                         capture_output=True, text=True, cwd=ROOT)
    tail = [l for l in res.stdout.strip().split("\n") if l.strip()]
    summary = tail[-1] if tail else "no output"
    failed = [l for l in tail if l.startswith("FAILED")]
    return res.returncode, summary, failed


def run_fontbakery(kind, files):
    exe = shutil.which("fontbakery")
    if not exe:
        return None
    with tempfile.TemporaryDirectory() as tmp:
        js = os.path.join(tmp, "fb.json")
        subprocess.run([exe, "check-universal", "--skip-network", "-q", "-n", "-l", "WARN", "--json", js] + files,
                       capture_output=True, text=True, cwd=ROOT)
        with open(js) as fh:
            data = json.load(fh)
    findings = collections.OrderedDict()
    for sec in data["sections"]:
        for chk in sec["checks"]:
            if chk["result"] in ("FAIL", "WARN", "ERROR", "FATAL"):
                m = re.search(r"FontBakeryCheck:([^>]+)>", str(chk["key"]))
                check_id = m.group(1) if m else str(chk["key"])
                msgs = []
                for log in chk["logs"]:
                    if log["status"] in ("FAIL", "WARN", "ERROR", "FATAL"):
                        msg = log["message"]
                        text = msg.get("message", "") if isinstance(msg, dict) else str(msg)
                        text = re.sub(r'File "[^"]*[\\/]', 'File "', text)      # no local paths in a committed report
                        names = sorted(set(re.findall(r"Glyph name: (\S+)", text)))
                        if names:
                            text = "Unexpected number of contours in: " + ", ".join(names)
                        msgs.append(" ".join(text.split())[:230])
                entry = findings.setdefault((chk["result"], check_id), {"fonts": 0, "msg": msgs[0] if msgs else "", "all": set()})
                entry["fonts"] += 1
                entry["all"].update(msgs)
    return data["result"], findings


def main():
    lines = ["# Varcoda Mono - validation report", "",
             "Generated by `tests/font-validation/validate.py`. Everything below was run on the compiled files in",
             "`fonts/ttf/` and `fonts/otf/` on **%s** (%s)." % (platform.system(), platform.platform()), ""]
    lines += ["## Tool versions", ""]
    for k, v in versions().items():
        lines.append("- %s: %s" % (k, v))
    lines.append("")

    code, summary, failed = run_pytest()
    lines += ["## Project test-suite (pytest)", "", "`%s`" % summary, ""]
    if failed:
        lines += ["Failures:", ""] + ["- `%s`" % f for f in failed] + [""]
    lines += ["`tests/font-validation/test_fonts.py` - tables, monospacing, vertical metrics, Unicode coverage, glyph names,",
              "names and style linking, weight order, look-alike characters, OpenType features (HarfBuzz), OTS sanitizer,",
              "FreeType at 12-16 px, fontconfig, UFO sources, outline hygiene, reproducible build.",
              "",
              "`tests/rendering-tests/test_rendering.py` - hinted rasterisation at 12-16 px (grid, baseline, x-height,",
              "look-alikes, letters that must not fuse), ligature cell containment, box-drawing seams, and two headless Chromium runs: the ten styles",
              "loaded as web fonts, and installed into a scratch font directory and used by family name through",
              "fontconfig (skipped without Chrome/Chromium or fontconfig, and on Windows, where chrome.exe returns no DOM).",
              "",
              "`tests/test_project.py` - links, heading anchors and file names in the documentation, its JSON and TOML examples,",
              "the contents and determinism of the release archives.", ""]

    worst = code
    for kind, files in (("TTF", [os.path.join("fonts", "ttf", "VarcodaMono-%s.ttf" % s) for s in STYLES]),
                        ("OTF", [os.path.join("fonts", "otf", "VarcodaMono-%s.otf" % s) for s in STYLES])):
        res = run_fontbakery(kind, files)
        lines += ["## fontbakery universal profile - %s" % kind, ""]
        if res is None:
            lines += ["fontbakery is not installed - skipped.", ""]
            continue
        result, findings = res
        order = ["FATAL", "ERROR", "FAIL", "WARN", "INFO", "SKIP", "PASS"]
        lines.append("Totals over the ten fonts: " + ", ".join("%s %d" % (k, result[k]) for k in order if k in result))
        lines.append("")
        if findings:
            lines += ["| Result | Check | Fonts | Finding | Assessment |", "| --- | --- | --- | --- | --- |"]
            for (status, check_id), entry in findings.items():
                note = NOTES.get(check_id, "**unreviewed**")
                msg = entry["msg"] if len(entry["all"]) <= 1 else " / ".join(sorted(entry["all"]))[:400]
                lines.append("| %s | `%s` | %d | %s | %s |" % (status, check_id, entry["fonts"],
                                                             msg.replace("|", "\\|"), note))
            lines.append("")
        if result.get("FAIL") or result.get("FATAL"):
            worst = worst or 1

    exe = shutil.which("ufolint")
    lines += ["## UFO sources (ufolint)", ""]
    if exe:
        srcs = [os.path.join("sources", "VarcodaMono-%s.ufo" % s) for s in STYLES]
        res = subprocess.run([exe] + srcs, capture_output=True, text=True, cwd=ROOT)
        passed = res.stdout.count("All ufolint tests passed!")
        lines += ["%d of %d sources pass all ufolint tests." % (passed, len(srcs)), ""]
        if passed != len(srcs):
            worst = worst or 1
    else:
        lines += ["ufolint is not installed - skipped.", ""]

    lines += ["## Not covered by this report", "",
              "No application was driven. Installing the fonts, and rendering in VS Code, Windows Terminal, PowerShell and",
              "JetBrains IDEs (DirectWrite / GDI ClearType) or on macOS, were **not** executed by this script.",
              "`tests/rendering-tests/index.html` is a self-contained page for checking a real machine by eye.", ""]
    with open(os.path.join(HERE, "REPORT.md"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))
    print("\n".join(lines[:0]) + "wrote tests/font-validation/REPORT.md  (%s)" % summary)
    return worst


if __name__ == "__main__":
    sys.exit(main())
